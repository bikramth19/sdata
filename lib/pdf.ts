import { PDFDocument, StandardFonts, rgb } from "pdf-lib";
import type { Student } from "@prisma/client";

// Standard PDF fonts only support WinAnsi; replace unsupported characters rather than crash.
const printable = (v: unknown) => String(v ?? "—").replace(/[^\x20-\x7e\xa0-\xff]/g, " ");
export async function studentPdf(student: Student, institutionName = "Monoline") {
  const pdf = await PDFDocument.create();
  const page = pdf.addPage([595,842]);
  const regular = await pdf.embedFont(StandardFonts.Helvetica);
  const bold = await pdf.embedFont(StandardFonts.HelveticaBold);
  const ink = rgb(.12,.13,.16), muted = rgb(.43,.46,.51);
  page.drawRectangle({ x:0, y:770, width:595, height:72, color:rgb(.12,.13,.16) });
  page.drawText(printable(institutionName).slice(0,40), {x:42,y:801,size:21,font:bold,color:rgb(1,1,1)});
  page.drawText("STUDENT REGISTRATION RECORD", {x:42,y:781,size:9,font:regular,color:rgb(.85,.85,.86)});
  page.drawText(printable(student.registrationNo), {x:42,y:733,size:18,font:bold,color:ink});
  page.drawText(`Registered ${student.registeredAt.toISOString().slice(0,10)}`,{x:42,y:714,size:10,font:regular,color:muted});
  const fields: [string,unknown][] = [
    ["Full name",`${student.firstName} ${student.lastName}`], ["Email",student.email], ["Phone",student.phone],
    ["Date of birth",student.dateOfBirth],["Gender",student.gender], ["Program",student.program],
    ["Guardian",student.guardianName], ["Guardian phone",student.guardianPhone],
    ["Address",student.address],["Status",student.status],["Notes",student.notes]
  ];
  let y = 667;
  for (const [key,value] of fields) {
    page.drawText(key.toUpperCase(),{x:42,y,size:9,font:bold,color:muted});
    const display = printable(value).slice(0,90);
    page.drawText(display,{x:205,y,size:11,font:regular,color:ink,maxWidth:345});
    y -= 46;
    page.drawLine({start:{x:42,y:y+22},end:{x:553,y:y+22},thickness:.5,color:rgb(.88,.89,.91)});
  }
  page.drawText("Generated by Monoline Student Registration",{x:42,y:58,size:9,font:regular,color:muted});
  return pdf.save();
}
export function pdfResponse(bytes: Uint8Array, filename: string) {
  const body = new ArrayBuffer(bytes.byteLength);
  new Uint8Array(body).set(bytes);
  return new Response(body, { headers: { "Content-Type":"application/pdf", "Content-Disposition":`attachment; filename="${filename}"`, "Cache-Control":"no-store" } });
}
